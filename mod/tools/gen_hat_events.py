"""Writes the Magic Hat's events (Multiverse) from the apworld's table: data/events_special_lightspeed.xml.append.

Based on ArchiHat by Trapper444. Each destination shows only once its item came in (run variable ap_hat_<key>,
set by the mod), and the reroute menu offers the hat once any of them did (ap_hat_on).
Run after any change to MAGIC_HAT_DESTINATIONS: python3 mod/tools/gen_hat_events.py [--check]
"""
import importlib.util
import sys
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
DATA = HERE.parents[1] / "apworld" / "ftl" / "data.py"
OUT = HERE.parent / "ArchipelagoFTL" / "data" / "events_special_lightspeed.xml.append"
MENUS = (("generic", "Look for a generic sector."), ("unique", "Look for a unique sector."),
         ("secret", "Look for a secret sector."))


def load_table():
    spec = importlib.util.spec_from_file_location("ftl_data", DATA)
    module = importlib.util.module_from_spec(spec)
    sys.modules["ftl_data"] = module
    spec.loader.exec_module(module)
    return module.MAGIC_HAT_DESTINATIONS


def build(destinations) -> str:
    lines = ["<!-- Generated by mod/tools/gen_hat_events.py: do not edit by hand. Magic Hat, after ArchiHat by "
             "Trapper444. -->", "<FTL>"]
    for menu_event in ("REROUTE_MENU", "REROUTE_MENU_LASTSTAND"):
        lines += [f'<mod:findName type="event" name="{menu_event}" panic="false">',
                  '\t<mod-append:choice hidden="true" req="ap_hat_on" blue="false">',
                  '\t\t<text>Use the Archipelago Magic Hat.</text>',
                  '\t\t<event><loadEvent>AP_HAT_MENU</loadEvent></event>',
                  '\t</mod-append:choice>',
                  '</mod:findName>']
    lines += ['<event name="AP_HAT_MENU">',
              '\t<text>The Magic Hat hums with the multiworld. Where should it take you?</text>',
              '\t<choice hidden="true">', '\t\t<text>Nevermind.</text>',
              '\t\t<event><loadEvent>ATLAS_MENU_NOEQUIPMENT</loadEvent></event>', '\t</choice>']
    for menu, text in MENUS:
        lines += [f'\t<choice hidden="true" req="ap_hat_{menu}" blue="false">', f'\t\t<text>{text}</text>',
                  f'\t\t<event><loadEvent>AP_HAT_MENU_{menu.upper()}</loadEvent></event>', '\t</choice>']
    lines.append('</event>')
    for menu, _ in MENUS:
        lines += [f'<event name="AP_HAT_MENU_{menu.upper()}">',
                  '\t<text>You consider where the Magic Hat could take you.</text>',
                  '\t<choice hidden="true">', '\t\t<text>Nevermind.</text>',
                  '\t\t<event><loadEvent>AP_HAT_MENU</loadEvent></event>', '\t</choice>']
        for key, kind, _sector, text in destinations:
            if kind == menu:
                lines += [f'\t<choice hidden="true" req="ap_hat_{key}" blue="false">',
                          f'\t\t<text>{escape(text)}</text>',
                          f'\t\t<event><loadEvent>AP_HAT_WARP_{key.upper()}</loadEvent></event>', '\t</choice>']
        lines.append('</event>')
    for key, _kind, sector, text in destinations:
        lines += [f'<event name="AP_HAT_WARP_{key.upper()}">',
                  f'\t<text>The Magic Hat shows you the way: {escape(text[0].lower() + text[1:])}</text>',
                  '\t<choice hidden="true">', '\t\t<text>Continue with the jump.</text>', '\t\t<event>',
                  '\t\t\t<text>You prepare to jump to the new co-ordinates, and change your flight path '
                  'accordingly.</text>',
                  '\t\t\t<variable name="loc_sector_count" op="add" val="-1"/>',
                  '\t\t\t<choice hidden="true">', '\t\t\t\t<text>Continue...</text>',
                  f'\t\t\t\t<event><secretSector>{sector}</secretSector></event>', '\t\t\t</choice>',
                  '\t\t</event>', '\t</choice>',
                  '\t<choice hidden="true">', '\t\t<text>Nevermind.</text>',
                  '\t\t<event><loadEvent>AP_HAT_MENU</loadEvent></event>', '\t</choice>', '</event>']
    lines.append("</FTL>")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = build(load_table())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("gen_hat_events: events_special_lightspeed.xml.append is out of date, run mod/tools/gen_hat_events.py")
            return 1
        print("gen_hat_events: Magic Hat events up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"written: {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
